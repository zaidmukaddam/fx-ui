// Lightweight i18n for fx-ui's user-facing UI strings.
//
// Scope: only strings the user reads in the interface (views/**, plus a few
// user-facing store messages). It deliberately does NOT cover the instructions
// and tool descriptions sent to the model — translating those would change the
// agent's behaviour.
//
// The chosen language lives in the store (`state.lang`), persisted across
// restarts. An empty string means "Automatic": follow the system language.

import { useApp } from "../store"

export type Lang = "en" | "zh-CN"

export const LANGUAGES: { value: Lang; label: string }[] = [
  { value: "en", label: "English" },
  { value: "zh-CN", label: "简体中文" },
]

/** Detect the system language, returning a language we ship a dictionary for. */
export function detectSystemLang(): Lang {
  const candidates = [
    process.env.LC_ALL,
    process.env.LC_MESSAGES,
    process.env.LANG,
    process.env.LANGUAGE,
  ].filter((value): value is string => Boolean(value))
  // Intl.DateTimeFormat resolves the OS locale even when env vars are unset.
  try {
    const resolved = new Intl.DateTimeFormat().resolvedOptions().locale
    if (resolved) candidates.push(resolved)
  } catch {
    // Intl unavailable — fall back to env vars only.
  }
  return candidates.some((value) => /^zh\b|zh[-_]|Chinese/i.test(value)) ? "zh-CN" : "en"
}

/** Resolve the effective language from a stored value ("" = follow system). */
export function resolveLang(stored: string): Lang {
  if (stored === "en" || stored === "zh-CN") return stored
  return detectSystemLang()
}

