const DICTS: Record<Lang, Dict> = { en, "zh-CN": zhCN }

/** Interpolate {name} placeholders in a template. */
function fill(template: string, params?: Record<string, string | number>): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (whole, key: string) =>
    key in params ? String(params[key]) : whole,
  )
}

export type Translate = (key: string, params?: Record<string, string | number>) => string

/** Build a translator for a given language, falling back to English then key. */
export function translator(lang: Lang): Translate {
  const dict = DICTS[lang]
  return (key, params) => fill(dict[key] ?? en[key] ?? key, params)
}

/** React hook: the translator for the current (reactive) language. */
export function useT(): Translate {
  const lang = resolveLang(useApp().lang)
  return translator(lang)
}
